// Verifies translation keys: run by `npm run check`.
//
// Fails when:
//  - a key passed to t() / $t() does not exist in the master locale (fr.json)
//  - a locale file is missing keys from fr.json, or defines extra ones
//  - a key in fr.json is never referenced anywhere in resources/js
//
// A key counts as used when it appears as a string literal ('nav.dashboard'),
// which covers keys stored in typed values such as nav items and layout titles.
// Dynamic keys built from a template literal (t(`language.${locale}`)) mark
// every key under that prefix as used.

/// <reference types="node" />

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const i18nDir = fileURLToPath(new URL('.', import.meta.url));
const localesDir = join(i18nDir, 'locales');
const sourceDir = join(i18nDir, '..');
const masterLocale = 'fr';

// Generated by Wayfinder, or the translations themselves.
const ignoredDirs = new Set(['actions', 'routes', 'wayfinder', 'locales']);

type Messages = { [key: string]: string | Messages };

function flattenKeys(messages: Messages, prefix = ''): string[] {
    return Object.entries(messages).flatMap(([key, value]) =>
        typeof value === 'object'
            ? flattenKeys(value, `${prefix}${key}.`)
            : [`${prefix}${key}`],
    );
}

function readLocale(file: string): Set<string> {
    const messages = JSON.parse(
        readFileSync(join(localesDir, file), 'utf8'),
    ) as Messages;

    return new Set(flattenKeys(messages));
}

function sourceFiles(dir: string): string[] {
    return readdirSync(dir).flatMap((entry) => {
        const path = join(dir, entry);

        if (statSync(path).isDirectory()) {
            return ignoredDirs.has(entry) ? [] : sourceFiles(path);
        }

        return /\.(vue|ts)$/.test(entry) ? [path] : [];
    });
}

const errors: string[] = [];
const masterKeys = readLocale(`${masterLocale}.json`);

for (const file of readdirSync(localesDir).filter((f) => f.endsWith('.json'))) {
    if (file === `${masterLocale}.json`) {
        continue;
    }

    const keys = readLocale(file);

    for (const key of masterKeys) {
        if (!keys.has(key)) {
            errors.push(`${file}: missing key "${key}"`);
        }
    }

    for (const key of keys) {
        if (!masterKeys.has(key)) {
            errors.push(`${file}: key "${key}" is not in ${masterLocale}.json`);
        }
    }
}

const usedKeys = new Set<string>();
const usedPrefixes = new Set<string>();

for (const file of sourceFiles(sourceDir)) {
    const source = readFileSync(file, 'utf8');
    const name = relative(sourceDir, file);

    for (const [, key] of source.matchAll(/\bt\(\s*['"]([^'"]+)['"]/g)) {
        if (!masterKeys.has(key)) {
            errors.push(`${name}: unknown translation key "${key}"`);
        }
    }

    for (const [, literal] of source.matchAll(/['"]([a-zA-Z0-9_.]+)['"]/g)) {
        if (masterKeys.has(literal)) {
            usedKeys.add(literal);
        }
    }

    for (const [, prefix] of source.matchAll(
        /\bt\(\s*`([a-zA-Z0-9_.]+)\$\{/g,
    )) {
        usedPrefixes.add(prefix);
    }
}

for (const key of masterKeys) {
    const usedByPrefix = [...usedPrefixes].some((prefix) =>
        key.startsWith(prefix),
    );

    if (!usedKeys.has(key) && !usedByPrefix) {
        errors.push(`${masterLocale}.json: unused key "${key}"`);
    }
}

if (errors.length > 0) {
    console.error(`Translation check failed (${errors.length}):`);

    for (const error of errors) {
        console.error(`  - ${error}`);
    }

    process.exit(1);
}

console.log(
    `pass: ${masterKeys.size} translation keys are defined in every locale and used`,
);
